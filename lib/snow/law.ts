// 조 번호가 없는 "조례"는 잡지 않는다
const CITE_RE = /자연재해대책법\s*제27조|지방자치법\s*제142조|조례\s*제(\d+(?:·\d+)*)조(?:\s*제\d+항)?/g

export interface CiteSpan {
  text: string
  keys: string[]
}

export function snowLawRefsIn(text: string): (string | CiteSpan)[] {
  const out: (string | CiteSpan)[] = []
  let last = 0
  for (const m of text.matchAll(CITE_RE)) {
    const i = m.index ?? 0
    if (i > last) out.push(text.slice(last, i))
    const keys = /^자연재해/.test(m[0]) ? ["law-27"] : /^지방자치법/.test(m[0]) ? ["lga-142"] : m[1].split("·").map((n) => `ord-${n}`)
    out.push({ text: m[0], keys: keys.filter((k) => k in SNOW_LAW_TEXTS) })
    last = i + m[0].length
  }
  if (last < text.length) out.push(text.slice(last))
  return out
}
