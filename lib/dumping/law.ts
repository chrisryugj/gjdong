// "조례·시행규칙"처럼 조 번호가 없는 말은 잡지 않는다
const CITE_RE = /폐기물관리법\s*(\d+)조|(?:구\s*)?(?:광진구\s*)?(?:폐기물관리\s*)?조례\s*(\d+(?:·\d+)*)조/g

export interface CiteSpan {
  text: string
  keys: string[] // LAW_TEXTS 키. 등록되지 않은 조문은 빈 배열
}

export function lawRefsIn(text: string): (string | CiteSpan)[] {
  const out: (string | CiteSpan)[] = []
  let last = 0
  for (const m of text.matchAll(CITE_RE)) {
    const i = m.index ?? 0
    if (i > last) out.push(text.slice(last, i))
    const keys = m[1] ? [`law-${m[1]}`] : m[2].split("·").map((n) => `ord-${n}`)
    out.push({ text: m[0], keys: keys.filter((k) => k in LAW_TEXTS) })
    last = i + m[0].length
  }
  if (last < text.length) out.push(text.slice(last))
  return out
}
